woodpecker_secret_name() {
	local app="$1" wanted="$2" manifest rule key name raw old_ifs
	manifest="$root/apps/$app/manifest.env"
	raw="$(env_value WOODPECKER_SECRET_NAMES "$manifest")"
	old_ifs="$IFS"
	IFS=','
	for rule in $raw; do
		[[ -n "$rule" ]] || continue
		key="${rule%%:*}"
		name="${rule#*:}"
		[[ "$key" =~ ^[A-Z][A-Z0-9_]*$ && "$name" =~ ^[A-Za-z_][A-Za-z0-9_-]*$ ]] ||
			die "invalid WOODPECKER_SECRET_NAMES entry: $app/$rule"
		if [[ "$key" == "$wanted" ]]; then
			IFS="$old_ifs"
			printf '%s\n' "$name"
			return 0
		fi
	done
	IFS="$old_ifs"
	printf '%s' "$wanted" | tr '[:upper:]' '[:lower:]'
}
woodpecker_secret_keys() {
	local app="$1" keys="$2" manifest mapping rule key result='' old_ifs
	manifest="$root/apps/$app/manifest.env"
	mapping="$(env_value WOODPECKER_SECRET_NAMES "$manifest")"
	if [[ -z "$mapping" ]]; then
		printf '%s\n' "$keys"
		return 0
	fi
	old_ifs="$IFS"
	IFS=','
	for rule in $mapping; do
		[[ -n "$rule" ]] || continue
		key="${rule%%:*}"
		csv_has "$keys" "$key" || continue
		result="${result:+$result,}$key"
	done
	IFS="$old_ifs"
	printf '%s\n' "$result"
}
conditional_secret_keys() {
	local manifest="$1" node="${2:-}" rule selector expected keys config_file override_file value result='' old_ifs raw
	config_file="$(dirname "$manifest")/$(env_value CONFIG_FILE "$manifest")"
	override_file="$root/config/cluster/overrides/$node/$(env_value APP_ID "$manifest").env"
	raw="$(env_value CONDITIONAL_SECRET_KEYS "$manifest")"
	old_ifs="$IFS"
	IFS=';'
	for rule in $raw; do
		[[ -n "$rule" ]] || continue
		selector="${rule%%=*}"
		expected="${rule#*=}"
		keys="${expected#*|}"
		expected="${expected%%|*}"
		value="$(env_value "$selector" "$override_file")"
		[[ -n "$value" ]] || value="$(env_value "$selector" "$config_file")"
		[[ "$value" == "$expected" ]] || continue
		result="${result:+$result,}$keys"
	done
	IFS="$old_ifs"
	printf '%s\n' "$result"
}
deployment_secret_keys() {
	local manifest="$1" raw item seen='' result='' old_ifs
	raw="$(env_value DEPLOYMENT_SECRET_KEYS "$manifest")"
	old_ifs="$IFS"
	IFS=','
	for item in $raw; do
		[[ -n "$item" ]] || continue
		csv_has "$seen" "$item" && continue
		seen="${seen:+$seen,}$item"
		result="${result:+$result,}$item"
	done
	IFS="$old_ifs"
	printf '%s\n' "$result"
}

render_consumer_secrets() {
	local app="$1" node="$2" dependency="$3" keys="$4" file key secret_name target_arg='' workflow_name secret_keys
	local depends_block='' secret_injections='' old_ifs
	file="$output/consumer-secrets-$app-$node.yml"
	workflow_name="consumer-secrets-$app-$node"
	secret_keys="$(woodpecker_secret_keys "$app" "$keys")"
	[[ "$node" == "$leader_id" ]] || target_arg=" --target-node $node"
	[[ -n "$dependency" ]] && depends_block=$'\ndepends_on:\n  - '"$dependency"$'\n'
	old_ifs="$IFS"
	IFS=','
	for key in $secret_keys; do
		[[ -n "$key" ]] || continue
		secret_name="$(woodpecker_secret_name "$app" "$key")"
		secret_injections="${secret_injections}      ${key}:"$'\n'"        from_secret: ${secret_name}"$'\n'
	done
	IFS="$old_ifs"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main
    evaluate: 'MANUAL_WORKFLOW == "$workflow_name"'
$depends_block
labels:
  node: $node
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$node")

steps:
  secrets:
    image: $runner_image
    pull: true
$runner_env_block
$secret_injections$volumes_common
    commands:
      - /usr/local/bin/configure-app-secrets $app$target_arg --non-interactive
EOF
}

render_consumer_stage() {
	local app="$1" node="$2" dependency="$3" file manifest migration_from stage_secret_keys generated_keys key secret_name
	local secret_injections='' command_lines='' old_ifs seen_stage_secrets=''
	file="$output/consumer-stage-$app-$node.yml"
	manifest="$root/apps/$app/manifest.env"
	migration_from="$(env_value IDENTITY_MIGRATION_FROM_APP_ID "$manifest")"
	write_consumer_header "$file" "$app" "$node" "$dependency"
	stage_secret_keys="$(deployment_secret_keys "$manifest")"
	if [[ "$(env_value RUNTIME_ENV_PROVISION "$manifest")" == stage ]]; then
		stage_secret_keys="${stage_secret_keys}${stage_secret_keys:+,}$(env_value NODE_SECRET_KEYS "$manifest"),$(conditional_secret_keys "$manifest" "$node")"
	fi
	if [[ -n "$stage_secret_keys" ]]; then
		generated_keys="$(env_value GENERATED_SECRET_KEYS "$manifest")"
		old_ifs="$IFS"
		IFS=','
		for key in $stage_secret_keys; do
			[[ -n "$key" ]] || continue
			csv_has "$generated_keys" "$key" && continue
			csv_has "$seen_stage_secrets" "$key" && continue
			seen_stage_secrets="${seen_stage_secrets:+$seen_stage_secrets,}$key"
			secret_name="$(woodpecker_secret_name "$app" "$key")"
			secret_injections="${secret_injections}      ${key}:"$'\n'"        from_secret: ${secret_name}"$'\n'
		done
		IFS="$old_ifs"
	fi
	if [[ -n "$migration_from" ]]; then
		command_lines="      - bash /opt/platform/control/current/ops/migrate-app-identity.sh prepare $app"$'\n'
	fi
	command_lines="${command_lines}      - /usr/local/bin/configure-app-secrets $app --target-node $node --ensure-generated"$'\n'
	if [[ -n "$stage_secret_keys" ]]; then
		command_lines="${command_lines}      - /usr/local/bin/configure-app-secrets $app --target-node $node --non-interactive"$'\n'
	fi
	if [[ -n "$migration_from" ]]; then
		command_lines="${command_lines}      - $ci_sha_guard DEPLOY_DEBUG_LEVEL=$deploy_debug_level CONSUMER_APP_ID=$app /usr/local/bin/platform-submit consumer-stage \"\$CI_COMMIT_SHA\" || { status=\$?; rollback_status=0; IDENTITY_MIGRATION_MANIFEST=/opt/platform/control/releases/\"\$CI_COMMIT_SHA\"/apps/$app/manifest.env bash /opt/platform/control/releases/\"\$CI_COMMIT_SHA\"/ops/migrate-app-identity.sh rollback $app || rollback_status=\$?; /usr/local/bin/platformctl recover || true; if [ \"\$rollback_status\" -ne 0 ]; then exit \"\$rollback_status\"; fi; exit \"\$status\"; }"
	else
		command_lines="${command_lines}      - $ci_sha_guard DEPLOY_DEBUG_LEVEL=$deploy_debug_level CONSUMER_APP_ID=$app /usr/local/bin/platform-submit consumer-stage \"\$CI_COMMIT_SHA\""
	fi
	cat >>"$file" <<EOF
  stage:
    image: $runner_image
    pull: true
$runner_env_block
$secret_injections$volumes_common
    commands:
$command_lines
EOF
}

