write_consumer_header() {
	local file="$1" app="$2" node="$3" dependencies="$4" dep depends_block='' old_ifs
	if [[ -n "$dependencies" ]]; then
		old_ifs="$IFS"
		IFS=','
		for dep in $dependencies; do
			[[ -n "$dep" ]] && depends_block="${depends_block}  - ${dep}"$'\n'
		done
		IFS="$old_ifs"
	fi
	depends_block="${depends_block}  - control-sync-${node}"$'\n'"  - name: foundation-reconcile-${node}"$'\n'"    optional: true"$'\n'"  - name: cluster-reconcile-${node}"$'\n'"    optional: true"$'\n'
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
skip_clone: true
when:
  - event: push
    branch: main
    path:
      include:
        - apps/$app/**
        - config/cluster/apps/$app.policy
        - config/cluster/overrides/**/$app.env
        - apps/$app/route*.caddy
        - apps/$app/images.lock.env
      on_empty: false

depends_on:
$depends_block
labels:
  node: $node
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$node")

steps:
EOF
}

