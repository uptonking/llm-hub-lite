#!/usr/bin/env bash
# shellcheck disable=SC2016
# SC2016: Woodpecker variables must stay literal in generated YAML.
set -Eeuo pipefail
umask 077

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
policy="${CLUSTER_POLICY_FILE:-$root/config/cluster/policy.env}"
output="${WOODPECKER_WORKFLOW_ROOT:-$root/.woodpecker}"
lock_output_root="$root/apps"
mode="${1:-generate}"
deployment_group_prefix='llm-hub-lite-node'

env_value() {
	local key="$1" file="$2" line value=''
	[[ -f "$file" ]] || return 0
	while IFS= read -r line || [[ -n "$line" ]]; do
		[[ "$line" == "$key="* ]] || continue
		value="${line#*=}"
	done <"$file"
	printf '%s\n' "$value"
}
value() { env_value "$1" "$policy"; }
deployment_group() {
	local node="$1"
	printf '%s-%s\n' "$deployment_group_prefix" "$node"
}
die() {
	printf 'generate-woodpecker-workflows: %s\n' "$*" >&2
	exit 1
}
deploy_debug_level="${DEPLOY_DEBUG_LEVEL:-$(value DEPLOY_DEBUG_LEVEL)}"
deploy_debug_level="${deploy_debug_level:-off}"
case "$deploy_debug_level" in off | warn | debug) ;; *) die 'DEPLOY_DEBUG_LEVEL must be off, warn, or debug' ;; esac
runner_image="${DEPLOY_RUNNER_IMAGE:-$(value DEPLOY_RUNNER_IMAGE)}"
[[ "$runner_image" =~ ^[^[:space:]]+@sha256:[0-9a-f]{64}$ ]] || die 'DEPLOY_RUNNER_IMAGE must be digest-pinned'
# shellcheck disable=SC2034 # used by sourced ops/generate-woodpecker-workflows-lib.sh
ci_sha_guard='if ! test -n "$CI_COMMIT_SHA" || ! printf "%s" "$CI_COMMIT_SHA" | grep -Eq "^[0-9a-f]{40}$"; then printf "CI_COMMIT_SHA must be a full 40-character lowercase commit SHA\\n" >&2; exit 2; fi;'
csv_has() {
	local csv=",${1//[[:space:]]/},"
	[[ "$csv" == *",$2,"* ]]
}
app_policy_file() {
	local manifest="$1" app rel
	app="$(env_value APP_ID "$manifest")"
	rel="$(env_value POLICY_FILE "$manifest")"
	[[ "$rel" == "cluster/apps/$app.policy" ]] || die "invalid app policy path: $manifest"
	printf '%s/config/%s\n' "$root" "$rel"
}

IMAGE_CACHE_LOADED=0
load_image_cache() {
	local line key val
	IMAGE_CACHE_LOADED=1
	[[ -f "$root/ops/images.apps.prod.env" ]] || return 0
	while IFS= read -r line || [[ -n "$line" ]]; do
		[[ "$line" =~ ^[A-Z][A-Z0-9_]*= ]] || continue
		key="${line%%=*}"
		val="${line#*=}"
		printf -v "IMG_CACHE_${key}" '%s' "$val"
	done <"$root/ops/images.apps.prod.env"
}

render_image_lock() {
	local manifest="$1" app destination key image var
	app="$(env_value APP_ID "$manifest")"
	destination="$lock_output_root/$app/images.lock.env"
	install -d -m 700 "$(dirname "$destination")"
	((IMAGE_CACHE_LOADED)) || load_image_cache
	{
		printf '# generated by ops/generate-woodpecker-workflows.sh; do not edit\n'
		for key in $(env_value IMAGE_KEYS "$manifest"); do
			[[ "$key" =~ ^[A-Z][A-Z0-9_]*$ ]] || die "invalid IMAGE_KEYS entry: $manifest/$key"
			var="IMG_CACHE_$key"
			image="${!var:-}"
			[[ "$image" =~ @sha256:[0-9a-f]{64}$ ]] || die "application image is missing or not digest-pinned: $app/$key"
			printf '%s=%s\n' "$key" "$image"
		done
	} >"$destination"
}

ids=()
followers=()
active_ids=()
reconcile_ids=()
consumer_nodes=()
active_consumer_nodes=()
retired_ids=()
ids_csv=''
old_ifs="$IFS"
IFS=','
for id in $(value NODE_IDS); do
	[[ -n "$id" ]] || continue
	[[ "$id" =~ ^[a-z][a-z0-9-]*$ ]] || die "invalid NODE_ID: $id"
	! csv_has "$ids_csv" "$id" || die "duplicate NODE_ID: $id"
	[[ -f "$root/config/cluster/nodes/$id.env" ]] || die "missing node descriptor: $id"
	[[ "$(env_value NODE_ID "$root/config/cluster/nodes/$id.env")" == "$id" ]] || die "descriptor NODE_ID mismatch: $id"
	state="$(env_value NODE_STATE "$root/config/cluster/nodes/$id.env")"
	case "$state" in
	joining) ;;
	draining) reconcile_ids+=("$id") ;;
	active)
		active_ids+=("$id")
		reconcile_ids+=("$id")
		;;
	retired) retired_ids+=("$id") ;;
	*) die "NODE_STATE must be joining, active, draining, or retired: $id" ;;
	esac
	ids+=("$id")
	ids_csv="${ids_csv:+$ids_csv,}$id"
done
IFS="$old_ifs"
((${#ids[@]} > 0)) || die 'NODE_IDS is empty'
leader_id="$(value LEADER_NODE_ID)"
repo_slug="$(value REPO_SLUG)"
[[ "$repo_slug" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die 'REPO_SLUG must be owner/repository'
csv_has "$ids_csv" "$leader_id" || die 'LEADER_NODE_ID is not in NODE_IDS'
[[ "$(env_value NODE_STATE "$root/config/cluster/nodes/$leader_id.env")" == active ]] || die "designated Leader node must be active: $leader_id"
for id in "${ids[@]}"; do
	[[ "$id" == "$leader_id" ]] && continue
	followers+=("$id")
	state="$(env_value NODE_STATE "$root/config/cluster/nodes/$id.env")"
	[[ "$state" == active || "$state" == draining ]] && consumer_nodes+=("$id")
	[[ "$state" == active ]] && active_consumer_nodes+=("$id")
done
((${#followers[@]} > 0)) || die 'at least one follower is required for consumer placement'

# Source templating and workflow generation routines.
generator_lib="$(dirname -- "${BASH_SOURCE[0]}")/generate-woodpecker-workflows-lib.sh"
[[ -f "$generator_lib" ]] || die "missing generator library: $generator_lib"
# shellcheck disable=SC1090
source "$generator_lib"

is_generated_file() {
	local file="$1" line=''
	[[ -r "$file" ]] || return 1
	IFS= read -r line <"$file" || true
	[[ "$line" == *'generated by ops/generate-woodpecker-workflows.sh'* ]]
}

remove_generated() {
	local file
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		is_generated_file "$file" || continue
		rm -f -- "$file"
	done
	for file in "$lock_output_root"/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		is_generated_file "$file" || continue
		rm -f -- "$file"
	done
}

check_dependency_closure() {
	local file dependency
	while IFS=' ' read -r file dependency || [[ -n "$file" ]]; do
		[[ -n "$dependency" ]] || continue
		[[ -f "$output/$dependency.yml" ]] || die "workflow dependency does not exist: $file -> $dependency"
	done < <(awk 'FNR==1 {f=FILENAME} /^depends_on:/ {active=1; next} active && /^  - name: / {sub(/^  - name: /, ""); print f, $0; next} active && /^  - / {sub(/^  - /, ""); print f, $0; next} active {active=0}' "$output"/*.yml)
}

render_all() {
	local manifest id previous
	install -d -m 700 "$output"
	for id in "${ids[@]}"; do
		render_control_sync "$id"
	done
	render_push_audit
	for id in "${reconcile_ids[@]}"; do
		if [[ "$id" == "$leader_id" ]]; then
			render_foundation_reconcile "$id" ''
		else
			render_foundation_reconcile "$id" "foundation-reconcile-$leader_id"
		fi
	done
	for manifest in "$root"/apps/*/manifest.env; do
		[[ -f "$manifest" ]] || continue
		render_image_lock "$manifest"
		render_consumer_workflows "$manifest"
	done
	render_cluster_reconcile "$leader_id" ''
	for id in "${reconcile_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_cluster_reconcile "$id" "cluster-reconcile-$leader_id"
	done
	previous=''
	render_manual_node foundation "$leader_id" "$previous" "$output/foundation-upgrade-$leader_id.yml"
	previous="foundation-upgrade-$leader_id"
	for id in "${active_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_manual_node foundation "$id" "$previous" "$output/foundation-upgrade-$id.yml"
		previous="foundation-upgrade-$id"
	done
	previous=''
	render_manual_node runner "$leader_id" "$previous" "$output/runner-upgrade-$leader_id.yml"
	previous="runner-upgrade-$leader_id"
	for id in "${active_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_manual_node runner "$id" "$previous" "$output/runner-upgrade-$id.yml"
		previous="runner-upgrade-$id"
	done
	previous=''
	for id in "${consumer_nodes[@]}"; do
		render_manual_node rollback "$id" "$previous" "$output/rollback-$id.yml"
		previous="rollback-$id"
	done
	render_manual_node rollback "$leader_id" "$previous" "$output/rollback-$leader_id.yml"
	for id in "${retired_ids[@]-}"; do
		[[ -n "$id" ]] || continue
		render_manual_node retire "$id" '' "$output/node-retire-$id.yml"
	done
	check_dependency_closure
}

copy_generated_stage() {
	local stage="$1" file target
	for file in "$stage"/*.yml; do
		[[ -f "$file" ]] || continue
		target="$output/$(basename "$file")"
		if ! cp -p "$file" "$target"; then return 1; fi
	done
	for file in "$stage"/apps/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		target="$lock_output_root/$(basename "$(dirname "$file")")/images.lock.env"
		install -d -m 700 "$(dirname "$target")"
		if ! cp -p "$file" "$target"; then return 1; fi
	done
}

generate_transaction() {
	local stage backup real_output real_lock_output_root file relative
	install -d -m 700 "$output" "$lock_output_root"
	stage="$(mktemp -d "${output}.staging.XXXXXX")"
	real_output="$output"
	real_lock_output_root="$lock_output_root"
	output="$stage"
	lock_output_root="$stage/apps"
	if ! render_all; then
		output="$real_output"
		lock_output_root="$real_lock_output_root"
		rm -rf -- "$stage"
		return 1
	fi
	output="$real_output"
	lock_output_root="$real_lock_output_root"
	backup="$(mktemp -d "${output}.backup.XXXXXX")"
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		is_generated_file "$file" || continue
		cp -p "$file" "$backup/$(basename "$file")" || {
			rm -rf -- "$stage" "$backup"
			return 1
		}
	done
	for file in "$lock_output_root"/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		is_generated_file "$file" || continue
		relative="apps/$(basename "$(dirname "$file")")/images.lock.env"
		install -d -m 700 "$backup/apps/$(basename "$(dirname "$file")")"
		cp -p "$file" "$backup/$relative" || {
			rm -rf -- "$stage" "$backup"
			return 1
		}
	done
	if ! remove_generated || ! copy_generated_stage "$stage"; then
		remove_generated || true
		for file in "$backup"/*.yml; do
			[[ -f "$file" ]] || continue
			cp -p "$file" "$output/$(basename "$file")" || true
		done
		for file in "$backup"/apps/*/images.lock.env; do
			[[ -f "$file" ]] || continue
			target="$lock_output_root/$(basename "$(dirname "$file")")/images.lock.env"
			install -d -m 700 "$(dirname "$target")"
			cp -p "$file" "$target" || true
		done
		rm -rf -- "$stage" "$backup"
		return 1
	fi
	rm -rf -- "$stage" "$backup"
}

case "$mode" in
generate) generate_transaction || die 'unable to apply generated workflow set atomically' ;;
--check)
	tmp="$(mktemp -d)"
	trap 'rm -rf -- "$tmp"' EXIT
	real_output="$output"
	real_lock_output_root="$lock_output_root"
	output="$tmp"
	lock_output_root="$tmp/apps"
	render_all
	output="$real_output"
	lock_output_root="$real_lock_output_root"
	for file in "$tmp"/*.yml; do
		target="$output/$(basename "$file")"
		cmp -s "$file" "$target" || die "workflow is stale or differs: $target"
	done
	for file in "$tmp"/apps/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		app="$(basename "$(dirname "$file")")"
		target="$lock_output_root/$app/images.lock.env"
		cmp -s "$file" "$target" || die "application image lock is stale or differs: $target"
	done
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		if head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh'; then
			[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
		fi
	done
	check_dependency_closure
	;;
*) die 'usage: generate-woodpecker-workflows.sh [generate|--check]' ;;
esac
