		printf 'depends_on:\n  - name: %s\n    optional: true\n  - control-sync-%s\n\n' "$dependency" "$id" >>"$file"
	else
		printf 'depends_on:\n  - control-sync-%s\n\n' "$id" >>"$file"
	fi
	cat >>"$file" <<EOF
labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$id")

steps:
  reconcile:
    image: llm-hub-lite/deploy-runner:current
    pull: false
EOF
	write_volumes >>"$file"
	cat >>"$file" <<EOF
    commands:
      - DEPLOY_DEBUG_LEVEL=$deploy_debug_level /usr/local/bin/platform-submit cluster-reconcile "\$CI_COMMIT_SHA"
EOF
}

