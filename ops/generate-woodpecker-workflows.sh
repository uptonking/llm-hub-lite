#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
policy="${CLUSTER_POLICY_FILE:-$root/config/cluster/policy.env}"
output="${WOODPECKER_WORKFLOW_ROOT:-$root/.woodpecker}"
mode="${1:-generate}"

value() { sed -n "s/^$1=//p" "$policy" | tail -n1; }
csv_items() { printf '%s\n' "$(value "$1")" | tr ',' '\n' | sed '/^[[:space:]]*$/d'; }
csv_has() {
	local list=",${1//[[:space:]]/},"
	[[ "$list" == *",$2,"* ]]
}
die() {
	printf 'generate-woodpecker-workflows: %s\n' "$*" >&2
	exit 1
}

ids=()
ids_csv=''
while IFS= read -r id; do
	[[ "$id" =~ ^[a-z][a-z0-9-]*$ ]] || die "invalid NODE_ID: $id"
	[[ ",$ids_csv," != *",$id,"* ]] || die "duplicate NODE_ID: $id"
	[[ -f "$root/config/cluster/nodes/$id.env" ]] || die "missing node descriptor: $id"
	[[ "$(sed -n 's/^NODE_ID=//p' "$root/config/cluster/nodes/$id.env" | tail -n1)" == "$id" ]] || die "descriptor NODE_ID mismatch: $id"
	ids+=("$id")
	ids_csv="${ids_csv:+$ids_csv,}$id"
done < <(csv_items NODE_IDS)
((${#ids[@]} > 0)) || die 'NODE_IDS is empty'
migration_id="$(value NEW_API_MIGRATION_NODE_ID)"
primary_id="$(value CLIPROXY_PRIMARY_NODE_ID)"
backup_id="$(value NEW_API_BACKUP_NODE_ID)"
leader_id="$(value LEADER_NODE_ID)"
repo_slug="$(value REPO_SLUG)"
[[ "$repo_slug" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die 'REPO_SLUG must be owner/repository'
[[ ",$ids_csv," == *",$leader_id,"* ]] || die 'LEADER_NODE_ID is not in NODE_IDS'

newapi_enabled=1
cliproxy_enabled=1
csv_has "$(value DISABLED_APPS)" newapi && newapi_enabled=0
csv_has "$(value DISABLED_APPS)" cliproxyapi && cliproxy_enabled=0
if ((newapi_enabled)); then
	[[ ",$ids_csv," == *",$backup_id,"* ]] || die 'NEW_API_BACKUP_NODE_ID is not in NODE_IDS'
	[[ ",$ids_csv," == *",$migration_id,"* ]] || die 'NEW_API_MIGRATION_NODE_ID is not in NODE_IDS'
	[[ "$leader_id" != "$migration_id" ]] || die 'NEW_API_MIGRATION_NODE_ID must be a follower'
	[[ "$(sed -n 's/^NEW_API_NODE_TYPE=//p' "$root/config/cluster/nodes/$migration_id.env" | tail -n1)" == master ]] || die 'migration node must use NEW_API_NODE_TYPE=master'
	master_count=0
	for id in "${ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		case "$(sed -n 's/^NEW_API_NODE_TYPE=//p' "$root/config/cluster/nodes/$id.env" | tail -n1)" in
		master) master_count=$((master_count + 1)) ;;
		slave) ;;
		*) die "follower $id must set NEW_API_NODE_TYPE to master or slave" ;;
		esac
	done
	((master_count == 1)) || die 'exactly one follower must use NEW_API_NODE_TYPE=master'
fi
if ((cliproxy_enabled)); then
	[[ ",$ids_csv," == *",$primary_id,"* ]] || die 'CLIPROXY_PRIMARY_NODE_ID is not in NODE_IDS'
	[[ "$leader_id" != "$primary_id" ]] || die 'CLIPROXY_PRIMARY_NODE_ID must be a follower'
fi

ordered=()
ordered+=("$leader_id")
if ((newapi_enabled)); then
	ordered+=("$migration_id")
fi
for id in "${ids[@]}"; do
	[[ "$id" == "${ordered[0]}" || ("$newapi_enabled" -eq 1 && "$id" == "$migration_id") ]] || ordered+=("$id")
done

render() {
	local id="$1" previous="$2" file="$3" event="$4"
	local dep=''
	if [[ -n "$previous" ]]; then
		if [[ "$event" == cluster ]]; then
			dep=$'\ndepends_on:\n  - cluster-reconcile-'"$previous"
		else
			dep=$'\ndepends_on:\n  - deploy-'"$previous"
		fi
	fi
	if [[ "$event" == cluster ]]; then
		cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: push
    branch: main
    path:
      include:
        - config/cluster/**
$dep

labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: llm-hub-lite-cluster-reconcile

steps:
  reconcile:
    image: llm-hub-lite/deploy-runner:current
    pull: false
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
    commands:
      - /usr/local/bin/platform-submit cluster-reconcile "\$CI_COMMIT_SHA"
EOF
	else
		cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: push
    branch: main
    path:
      exclude:
        - config/cluster/**

labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug
$dep
concurrency:
  limit: 1
  group: llm-hub-lite-production

steps:
  deploy:
    image: llm-hub-lite/deploy-runner:current
    pull: false
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
    commands:
      - /usr/local/bin/platform-submit deploy "\$CI_COMMIT_SHA"
EOF
	fi
}

render_app_upgrade() {
	local id="$1" file="$2"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main

labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: llm-hub-lite-app-upgrade

steps:
  upgrade:
    image: llm-hub-lite/deploy-runner:current
    pull: false
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
    commands:
      - /usr/local/bin/platform-submit app-upgrade "\$CI_COMMIT_SHA"
EOF
}

render_manual_node() {
	local kind="$1" id="$2" previous="$3" file="$4" command submit_command
	case "$kind" in
	foundation) command="foundation-upgrade \"\$CI_COMMIT_SHA\"" ;;
	runner) command="upgrade-runner" ;;
	rollback) command="rollback \"\${ROLLBACK_TARGET:-previous}\"" ;;
	*) die "unknown manual workflow kind: $kind" ;;
	esac
	submit_command="/usr/local/bin/platform-submit $command"
	[[ "$kind" == runner ]] && submit_command="/usr/local/bin/upgrade-runner"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main

EOF
	if [[ -n "$previous" ]]; then
		case "$kind" in
		foundation | runner) printf 'depends_on:\n  - %s-upgrade-%s\n\n' "$kind" "$previous" >>"$file" ;;
		rollback) printf 'depends_on:\n  - rollback-%s\n\n' "$previous" >>"$file" ;;
		*) die "unknown manual workflow kind: $kind" ;;
		esac
	fi
	cat >>"$file" <<EOF
labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: llm-hub-lite-$kind

steps:
  $kind:
    image: llm-hub-lite/deploy-runner:current
    pull: false
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platformctl:/usr/local/bin/platformctl:ro
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
      - /usr/local/bin/deploy-controller:/usr/local/bin/deploy-controller:ro
      - /usr/local/bin/git-auth.sh:/usr/local/bin/git-auth.sh:ro
      - /usr/local/bin/backup-platform:/usr/local/bin/backup-platform:ro
      - /usr/local/bin/upgrade-runner:/usr/local/bin/upgrade-runner:ro
    commands:
      - $submit_command
EOF
}

check_dependency_closure() {
	local file dependency
	while IFS= read -r file; do
		while IFS= read -r dependency; do
			[[ -n "$dependency" ]] || continue
			[[ -f "$output/$dependency.yml" ]] || die "workflow dependency does not exist: $file -> $dependency"
		done < <(awk '
      /^depends_on:/ { in_dep=1; next }
      in_dep && /^  - / { sub(/^  - /, ""); print; next }
      in_dep { in_dep=0 }
    ' "$file")
	done < <(find "$output" -maxdepth 1 -type f -name '*.yml' -print | sort)
}

sync_manual_workflows() {
	local file
	for file in "$output"/deploy-*.yml "$output"/cluster-reconcile-*.yml "$output"/app-upgrade-*.yml \
		"$output"/foundation-upgrade-*.yml "$output"/runner-upgrade-*.yml "$output"/rollback-*.yml "$output/deploy-smoke.yml"; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		rm -f -- "$file"
	done
}

generate() {
	install -d -m 700 "$output"
	sync_manual_workflows
	local id previous='' file
	for id in "${ordered[@]}"; do
		file="$output/deploy-$id.yml"
		render "$id" "$previous" "$file" deploy
		previous="$id"
	done
	local cluster_previous=''
	for id in "${ids[@]}"; do
		render "$id" "$cluster_previous" "$output/cluster-reconcile-$id.yml" cluster
		cluster_previous="$id"
		[[ "$id" == "$leader_id" ]] || render_app_upgrade "$id" "$output/app-upgrade-$id.yml"
	done
	{
		printf '%s\n' '# generated by ops/generate-woodpecker-workflows.sh; do not edit'
		printf '%s\n' 'when:' '  - event: push' '    branch: main' '    path:' '      exclude:' '        - config/cluster/**' '' 'depends_on:'
		for id in "${ordered[@]}"; do printf '  - deploy-%s\n' "$id"; done
		printf '%s\n' '' 'labels:' "  node: $leader_id" '  deployment: "true"' '  target: production' "  repo: $repo_slug" '' 'concurrency:' '  limit: 1' '  group: llm-hub-lite-production' '' 'steps:' '  smoke:' '    image: llm-hub-lite/deploy-runner:current' '    pull: false' '    volumes:' '      - /var/run/docker.sock:/var/run/docker.sock' '      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite' '      - /opt/platform:/opt/platform' '      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite' '      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite' '      - /etc/llm-hub-lite:/etc/llm-hub-lite' '      - /usr/local/bin/platformctl:/usr/local/bin/platformctl:ro' '    commands:' '      - /usr/local/bin/platformctl health' '      - /usr/local/bin/platformctl smoke all'
	} >"$output/deploy-smoke.yml"
	local previous=''
	for id in "${ordered[@]}"; do
		render_manual_node foundation "$id" "$previous" "$output/foundation-upgrade-$id.yml"
		render_manual_node runner "$id" "$previous" "$output/runner-upgrade-$id.yml"
		previous="$id"
	done
	previous=''
	for id in "${ordered[@]}"; do
		[[ "$id" == "$leader_id" ]] || continue
		for worker in "${ids[@]}"; do [[ "$worker" != "$leader_id" ]] && render_manual_node rollback "$worker" "$previous" "$output/rollback-$worker.yml" && previous="$worker"; done
		render_manual_node rollback "$leader_id" "$previous" "$output/rollback-$leader_id.yml"
	done
	check_dependency_closure
}

check_manual_workflows() {
	local file
	for file in "$output"/foundation-upgrade-*.yml "$output"/runner-upgrade-*.yml "$output"/rollback-*.yml; do
		[[ -f "$file" ]] || die "missing manual workflow: $file"
		grep -Fqx "  repo: $repo_slug" "$file" || die "manual workflow has stale repo label: $file"
	done
	while IFS= read -r file; do
		[[ -f "$file" ]] || continue
		if head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh'; then
			[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
		fi
	done < <(find "$output" -mindepth 1 -maxdepth 1 -type f -name '*.yml' -print | sort)
}

case "$mode" in
generate) generate ;;
--check)
	tmp="$(mktemp -d)"
	trap 'rm -rf -- "$tmp"' EXIT
	real_output="$output"
	output="$tmp"
	generate
	output="$real_output"
	for file in "$tmp"/*.yml; do
		target="$output/$(basename "$file")"
		cmp -s "$file" "$target" || die "workflow is stale or differs: $target"
	done
	for file in "$output"/deploy-*.yml "$output"/cluster-reconcile-*.yml "$output"/app-upgrade-*.yml; do
		[[ -f "$file" ]] || continue
		[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
	done
	check_manual_workflows
	;;
*) die 'usage: generate-woodpecker-workflows.sh [generate|--check]' ;;
esac
