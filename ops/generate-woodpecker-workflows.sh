render_manual_node() {
	local kind="$1" id="$2" previous="$3" file="$4" command submit_command
	case "$kind" in
	foundation) command="foundation-upgrade \"\$CI_COMMIT_SHA\"" ;;
	runner) command="upgrade-runner" ;;
	rollback) command="rollback \"\${ROLLBACK_TARGET:-previous}\"" ;;
	*) die "unknown manual workflow kind: $kind" ;;
	esac
	submit_command="/usr/local/bin/platform-submit $command"
	[[ "$kind" == runner ]] && submit_command="/usr/local/bin/upgrade-runner"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main

EOF
	if [[ -n "$previous" ]]; then
		case "$kind" in
		foundation | runner) printf 'depends_on:\n  - %s-upgrade-%s\n\n' "$kind" "$previous" >>"$file" ;;
		rollback) printf 'depends_on:\n  - rollback-%s\n\n' "$previous" >>"$file" ;;
		*) die "unknown manual workflow kind: $kind" ;;
		esac
	fi
	cat >>"$file" <<EOF
labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $deployment_group

steps:
  $kind:
    image: llm-hub-lite/deploy-runner:current
    pull: false
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platformctl:/usr/local/bin/platformctl:ro
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
      - /usr/local/bin/deploy-controller:/usr/local/bin/deploy-controller:ro
      - /usr/local/bin/git-auth.sh:/usr/local/bin/git-auth.sh:ro
      - /usr/local/bin/backup-platform:/usr/local/bin/backup-platform:ro
      - /usr/local/bin/upgrade-runner:/usr/local/bin/upgrade-runner:ro
    commands:
      - $submit_command
EOF
}

check_dependency_closure() {
	local file dependency
	while IFS= read -r file; do
		while IFS= read -r dependency; do
			[[ -n "$dependency" ]] || continue
			[[ -f "$output/$dependency.yml" ]] || die "workflow dependency does not exist: $file -> $dependency"
		done < <(awk '
      /^depends_on:/ { in_dep=1; next }
      in_dep && /^  - / { sub(/^  - /, ""); print; next }
      in_dep { in_dep=0 }
    ' "$file")
	done < <(find "$output" -maxdepth 1 -type f -name '*.yml' -print | sort)
}

sync_manual_workflows() {
	local file
	for file in "$output"/deploy-*.yml "$output"/cluster-reconcile-*.yml "$output"/app-upgrade-*.yml \
		"$output"/singleton-*.yml "$output"/foundation-upgrade-*.yml "$output"/runner-upgrade-*.yml "$output"/rollback-*.yml "$output/deploy-smoke.yml"; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		rm -f -- "$file"
	done
}

generate() {
	install -d -m 700 "$output"
	sync_manual_workflows
	local id previous='' file
	for id in "${ordered[@]}"; do
		file="$output/deploy-$id.yml"
		render "$id" "$previous" "$file" deploy
		previous="$id"
	done
	local cluster_previous=''
	for id in "${ids[@]}"; do
		render "$id" "$cluster_previous" "$output/cluster-reconcile-$id.yml" cluster
		cluster_previous="$id"
		[[ "$id" == "$leader_id" ]] || render_app_upgrade "$id" "$output/app-upgrade-$id.yml"
	done
	for app in "${singleton_apps[@]}"; do render_singleton_workflows "$app"; done
	{
		printf '%s\n' '# generated by ops/generate-woodpecker-workflows.sh; do not edit'
		printf '%s\n' 'when:' '  - event: push' '    branch: main' '    path:' '      include:'
		printf '%s' "$app_source_paths"
		printf '%s\n' '        - config/Caddyfile' '        - config/foundation-routes.d/**' '        - config/routes.d/**' '' 'depends_on:'
		for id in "${ordered[@]}"; do printf '  - deploy-%s\n' "$id"; done
		printf '%s\n' '' 'labels:' "  node: $leader_id" '  deployment: "true"' '  target: production' "  repo: $repo_slug" '' 'concurrency:' '  limit: 1' "  group: $deployment_group" '' 'steps:' '  smoke:' '    image: llm-hub-lite/deploy-runner:current' '    pull: false' '    volumes:' '      - /var/run/docker.sock:/var/run/docker.sock' '      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite' '      - /opt/platform:/opt/platform' '      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite' '      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite' '      - /etc/llm-hub-lite:/etc/llm-hub-lite' '      - /usr/local/bin/platformctl:/usr/local/bin/platformctl:ro' '    commands:' '      - /usr/local/bin/platformctl health' '      - /usr/local/bin/platformctl smoke all'
	} >"$output/deploy-smoke.yml"
	local previous=''
	for id in "${ordered[@]}"; do
		render_manual_node foundation "$id" "$previous" "$output/foundation-upgrade-$id.yml"
		render_manual_node runner "$id" "$previous" "$output/runner-upgrade-$id.yml"
		previous="$id"
	done
	previous=''
	for id in "${ordered[@]}"; do
		[[ "$id" == "$leader_id" ]] || continue
		for worker in "${ids[@]}"; do [[ "$worker" != "$leader_id" ]] && render_manual_node rollback "$worker" "$previous" "$output/rollback-$worker.yml" && previous="$worker"; done
		render_manual_node rollback "$leader_id" "$previous" "$output/rollback-$leader_id.yml"
	done
	check_dependency_closure
}

check_manual_workflows() {
	local file
	for file in "$output"/foundation-upgrade-*.yml "$output"/runner-upgrade-*.yml "$output"/rollback-*.yml; do
		[[ -f "$file" ]] || die "missing manual workflow: $file"
		grep -Fqx "  repo: $repo_slug" "$file" || die "manual workflow has stale repo label: $file"
	done
	while IFS= read -r file; do
		[[ -f "$file" ]] || continue
		if head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh'; then
			[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
		fi
	done < <(find "$output" -mindepth 1 -maxdepth 1 -type f -name '*.yml' -print | sort)
}

case "$mode" in
generate) generate ;;
--check)
	tmp="$(mktemp -d)"
	trap 'rm -rf -- "$tmp"' EXIT
	real_output="$output"
	output="$tmp"
	generate
	output="$real_output"
	for file in "$tmp"/*.yml; do
		target="$output/$(basename "$file")"
		cmp -s "$file" "$target" || die "workflow is stale or differs: $target"
	done
	for file in "$output"/deploy-*.yml "$output"/cluster-reconcile-*.yml "$output"/app-upgrade-*.yml "$output"/singleton-*.yml; do
		[[ -f "$file" ]] || continue
		[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
	done
	check_manual_workflows
	;;
*) die 'usage: generate-woodpecker-workflows.sh [generate|--check]' ;;
esac
