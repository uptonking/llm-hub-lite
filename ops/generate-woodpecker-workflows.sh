render_consumer_workflows() {
	local manifest="$1" app placement upstream ingress policy_file enabled nodes node previous='' publish_name seen='' count=0 undesired='' primary_key primary stage_dependency='' target cluster_keys node_keys conditional_keys secret_keys migration_from key migration_value finalize_dependency
	app="$(env_value APP_ID "$manifest")"
	placement="$(env_value PLACEMENT "$manifest")"
	upstream="$(env_value UPSTREAM_MODE "$manifest")"
	ingress="$(env_value INGRESS_MODE "$manifest")"
	ingress="${ingress:-leader-proxy}"
	[[ "$app" == "$(basename "$(dirname "$manifest")")" && "$app" =~ ^[a-z][a-z0-9-]*$ ]] || die "invalid APP_ID: $manifest"
	[[ "$(env_value MANIFEST_VERSION "$manifest")" == 5 ]] || die "unsupported application manifest version: $manifest"
	[[ "$placement" == consumer ]] || die "application placement must be consumer: $manifest"
	policy_file="$(app_policy_file "$manifest")"
	[[ -f "$policy_file" ]] || die "missing app policy: $app"
	enabled="$(env_value ENABLED "$policy_file")"
	case "$enabled" in true | false) ;; *) die "app policy ENABLED must be true or false: $app" ;; esac
	nodes="$(env_value NODES "$policy_file")"
	[[ -n "$nodes" ]] || die "application policy NODES is empty: $app"
	while IFS= read -r node; do
		[[ "$node" =~ ^[a-z][a-z0-9-]*$ ]] || die "invalid consumer node: $app/$node"
		if ! csv_has "$ids_csv" "$node"; then
			# Direct applications may be committed ahead of a joining inventory
			# entry. Defer workflow generation until that follower is enrolled;
			# runtime validation still rejects an enabled placement that is absent.
			[[ "$ingress" == direct ]] && {
				printf 'generate-woodpecker-workflows: deferring direct app until node is enrolled: %s/%s\n' "$app" "$node" >&2
				return 0
			}
			die "consumer node is absent from NODE_IDS: $app/$node"
		fi
		[[ "$node" != "$leader_id" ]] || die "consumer node must be an active follower: $app/$node"
		if [[ "$enabled" == true ]]; then
			if [[ "$(env_value NODE_STATE "$root/config/cluster/nodes/$node.env")" != active ]]; then
				[[ "$ingress" == direct ]] && {
					printf 'generate-woodpecker-workflows: deferring direct app until node is active: %s/%s\n' "$app" "$node" >&2
					return 0
				}
				die "consumer node must be an active follower: $app/$node"
			fi
		fi
		! csv_has "$seen" "$node" || die "duplicate consumer node: $app/$node"
		seen="${seen:+$seen,}$node"
		count=$((count + 1))
	done < <(printf '%s\n' "$nodes" | tr ',' '\n')
	case "$upstream" in
	singleton) ((count == 1)) || die "singleton application must target exactly one follower: $app" ;;
	active-active) ((count >= 1)) || die "$upstream application requires a follower: $app" ;;
	active-passive)
		((count >= 1)) || die "$upstream application requires a follower: $app"
		primary_key="$(env_value PRIMARY_NODE_KEY "$manifest")"
		[[ "$primary_key" =~ ^[A-Z][A-Z0-9_]*$ ]] || die "active-passive application requires PRIMARY_NODE_KEY: $app"
		primary="$(env_value "$primary_key" "$policy_file")"
		csv_has "$nodes" "$primary" || die "active-passive primary is absent from NODES: $app/$primary"
		;;
	*) die "unsupported UPSTREAM_MODE for $app: $upstream" ;;
	esac
	migration_from="$(env_value IDENTITY_MIGRATION_FROM_APP_ID "$manifest")"
	if [[ -n "$migration_from" ]]; then
		[[ "$upstream" == singleton && "$migration_from" =~ ^[a-z][a-z0-9-]*$ && "$migration_from" != "$app" ]] || die "invalid identity migration source: $app/$migration_from"
		for key in IDENTITY_MIGRATION_FROM_DATA_ROOT_REL IDENTITY_MIGRATION_FROM_RUNTIME_ENV_FILE IDENTITY_MIGRATION_FROM_COMPOSE_PROJECT IDENTITY_MIGRATION_FROM_NETWORK IDENTITY_MIGRATION_FROM_ENV_PREFIX IDENTITY_MIGRATION_TO_ENV_PREFIX IDENTITY_MIGRATION_TO_NETWORK; do
			migration_value="$(env_value "$key" "$manifest")"
			[[ -n "$migration_value" ]] || die "identity migration requires $key: $app"
		done
	fi
	if [[ "$app" == newapi && "$enabled" == true ]]; then
		for primary_key in NEW_API_MIGRATION_NODE_ID NEW_API_BACKUP_NODE_ID; do
			primary="$(env_value "$primary_key" "$policy_file")"
			csv_has "$nodes" "$primary" || die "$primary_key is absent from New API NODES: $primary"
		done
	fi
	if [[ "$enabled" == true ]]; then
		while IFS= read -r node; do
			# Active-active replicas are independent.  Singleton and active-passive
			# ordering is applied below where the application semantics require it.
			stage_dependency=''
			if [[ "$upstream" == active-passive && "$node" != "$primary" ]]; then
				stage_dependency="consumer-stage-$app-$primary"
			fi
			render_consumer_stage "$app" "$node" "$stage_dependency"
		done < <(printf '%s\n' "$nodes" | tr ',' '\n')
	fi
	# `previous` is retained for publish dependencies below; it is not used to
	# chain independent stage jobs.
	previous=''
	if [[ "$enabled" == true ]]; then
		while IFS= read -r node; do
			[[ -n "$node" ]] || continue
			previous="${previous}${previous:+,}consumer-stage-$app-$node"
		done < <(printf '%s\n' "$nodes" | tr ',' '\n')
	fi
	if [[ "$ingress" == direct && "$enabled" == true ]]; then
		target="${nodes%%,*}"
		render_direct_publish "$app" "$target" "$previous"
		publish_name="direct-publish-$app"
	else
		# Disabled direct apps still need a Leader cleanup transaction, but must
		# never invoke direct-publish (which assumes an active follower listener).
		render_consumer_publish "$app" "$previous"
		publish_name="consumer-publish-$app"
	fi
	for node in "${consumer_nodes[@]}"; do
		if [[ "$enabled" != true ]] || ! csv_has "$nodes" "$node"; then
			undesired="${undesired}${node}"$'\n'
		fi
	done
	previous="$publish_name"
	while IFS= read -r node; do
		[[ -n "$node" ]] || continue
		render_consumer_stop "$app" "$node" "$publish_name"
	done <<<"$undesired"
	if [[ "$enabled" == true && "$upstream" == singleton ]]; then
		target="${nodes%%,*}"
		# Finalization must wait for all stale-node cleanup, but those cleanup
		# jobs themselves run concurrently on their respective node groups.
		finalize_dependency="$publish_name"
		while IFS= read -r node; do
			[[ -n "$node" ]] || continue
			finalize_dependency="${finalize_dependency}${finalize_dependency:+,}consumer-stop-$app-$node"
		done <<<"$undesired"
		render_consumer_finalize "$app" "$target" "$finalize_dependency"
	fi
	if [[ "$enabled" == true ]]; then
		cluster_keys="$(env_value CLUSTER_SECRET_KEYS "$manifest")"
		node_keys="$(env_value NODE_SECRET_KEYS "$manifest")"
		conditional_keys="$(conditional_secret_keys "$manifest" "$leader_id")"
		# Conditional credentials for singleton consumers belong only to the
		# selected follower.  Cluster-wide secrets still need a Leader workflow;
		# active-active consumers continue to provision conditional credentials on
		# the Leader and each selected follower.
		if [[ -n "$cluster_keys" || ("$upstream" != singleton && -n "$conditional_keys") ]]; then
			render_consumer_secrets "$app" "$leader_id" '' "$cluster_keys,$conditional_keys"
		fi
		# Node-local secrets belong only on the nodes selected by this app's
		# placement policy.  Cleanup workflows above still cover active nodes
		# removed from placement, but they must not receive new credentials.
		while IFS= read -r node; do
			[[ -n "$node" ]] || continue
			conditional_keys="$(conditional_secret_keys "$manifest" "$node")"
			secret_keys="$cluster_keys"
			[[ -z "$conditional_keys" ]] || secret_keys="${secret_keys:+$secret_keys,}$conditional_keys"
			[[ -z "$node_keys" ]] || secret_keys="${secret_keys:+$secret_keys,}$node_keys"
			[[ -n "$secret_keys" ]] || continue
			render_consumer_secrets "$app" "$node" '' "$secret_keys"
		done < <(printf '%s\n' "$nodes" | tr ',' '\n')
	fi
}

render_manual_node() {
	local kind="$1" id="$2" previous="$3" file="$4" command submit workflow_name
	workflow_name="${file##*/}"
	workflow_name="${workflow_name%.yml}"
	case "$kind" in
	foundation) command='foundation-upgrade "$CI_COMMIT_SHA"' ;;
	runner) command='upgrade-runner' ;;
	rollback) command='rollback "${ROLLBACK_TARGET:-previous}"' ;;
	retire) command='node-retire "$CI_COMMIT_SHA"' ;;
	*) die "unknown manual workflow kind: $kind" ;;
	esac
	submit="/usr/local/bin/platform-submit $command"
	[[ "$kind" == runner ]] && submit='/usr/local/bin/upgrade-runner'
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main
    evaluate: 'MANUAL_WORKFLOW == "$workflow_name"'
EOF
	[[ -z "$previous" ]] || printf '\ndepends_on:\n  - %s\n' "$previous" >>"$file"
	cat >>"$file" <<EOF

labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$id")

steps:
  $kind:
    image: llm-hub-lite/deploy-runner:current
    pull: false
EOF
	write_volumes >>"$file"
	cat >>"$file" <<EOF
      - /usr/local/bin/deploy-controller:/usr/local/bin/deploy-controller:ro
      - /usr/local/bin/git-auth.sh:/usr/local/bin/git-auth.sh:ro
      - /usr/local/bin/backup-platform:/usr/local/bin/backup-platform:ro
      - /usr/local/bin/upgrade-runner:/usr/local/bin/upgrade-runner:ro
    commands:
      - $submit
EOF
}

remove_generated() {
	local file
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		rm -f -- "$file"
	done
	for file in "$lock_output_root"/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		rm -f -- "$file"
	done
}
check_dependency_closure() {
	local file dependency
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		while IFS= read -r dependency; do
			[[ -n "$dependency" ]] || continue
			[[ -f "$output/$dependency.yml" ]] || die "workflow dependency does not exist: $file -> $dependency"
		done < <(awk '/^depends_on:/ {active=1; next} active && /^  - name: / {sub(/^  - name: /, ""); print; next} active && /^  - / {sub(/^  - /, ""); print; next} active {active=0}' "$file")
	done
}
render_all() {
	local manifest id previous
	install -d -m 700 "$output"
	for id in "${ids[@]}"; do
		render_control_sync "$id" ''
	done
	render_push_audit
	for id in "${reconcile_ids[@]}"; do
		if [[ "$id" == "$leader_id" ]]; then
			render_foundation_reconcile "$id" ''
		else
			render_foundation_reconcile "$id" "foundation-reconcile-$leader_id"
		fi
	done
	for manifest in "$root"/apps/*/manifest.env; do
		[[ -f "$manifest" ]] || continue
		render_image_lock "$manifest"
		render_consumer_workflows "$manifest"
	done
	render_cluster_reconcile "$leader_id" ''
	for id in "${reconcile_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_cluster_reconcile "$id" "cluster-reconcile-$leader_id"
	done
	previous=''
	render_manual_node foundation "$leader_id" "$previous" "$output/foundation-upgrade-$leader_id.yml"
	previous="foundation-upgrade-$leader_id"
	for id in "${active_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_manual_node foundation "$id" "$previous" "$output/foundation-upgrade-$id.yml"
		previous="foundation-upgrade-$id"
	done
	previous=''
	render_manual_node runner "$leader_id" "$previous" "$output/runner-upgrade-$leader_id.yml"
	previous="runner-upgrade-$leader_id"
	for id in "${active_ids[@]}"; do
		[[ "$id" == "$leader_id" ]] && continue
		render_manual_node runner "$id" "$previous" "$output/runner-upgrade-$id.yml"
		previous="runner-upgrade-$id"
	done
	previous=''
	for id in "${consumer_nodes[@]}"; do
		render_manual_node rollback "$id" "$previous" "$output/rollback-$id.yml"
		previous="rollback-$id"
	done
	render_manual_node rollback "$leader_id" "$previous" "$output/rollback-$leader_id.yml"
	# Bash 3.2 treats an empty array expansion as unbound under `set -u`.
	# The default cluster has no retired nodes, so tolerate the one empty item.
	for id in "${retired_ids[@]-}"; do
		[[ -n "$id" ]] || continue
		render_manual_node retire "$id" '' "$output/node-retire-$id.yml"
	done
	check_dependency_closure
}

copy_generated_stage() {
	local stage="$1" file target
	for file in "$stage"/*.yml; do
		[[ -f "$file" ]] || continue
		target="$output/$(basename "$file")"
		if ! cp -p "$file" "$target"; then return 1; fi
	done
	for file in "$stage"/apps/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		target="$lock_output_root/$(basename "$(dirname "$file")")/images.lock.env"
		install -d -m 700 "$(dirname "$target")"
		if ! cp -p "$file" "$target"; then return 1; fi
	done
}

generate_transaction() {
	local stage backup real_output real_lock_output_root file relative
	install -d -m 700 "$output" "$lock_output_root"
	stage="$(mktemp -d "${output}.staging.XXXXXX")"
	real_output="$output"
	real_lock_output_root="$lock_output_root"
	output="$stage"
	lock_output_root="$stage/apps"
	if ! render_all; then
		output="$real_output"
		lock_output_root="$real_lock_output_root"
		rm -rf -- "$stage"
		return 1
	fi
	output="$real_output"
	lock_output_root="$real_lock_output_root"
	# Render and dependency validation have succeeded. Keep a private copy of
	# every generated artifact so an interrupted apply can restore it exactly.
	backup="$(mktemp -d "${output}.backup.XXXXXX")"
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		cp -p "$file" "$backup/$(basename "$file")" || {
			rm -rf -- "$stage" "$backup"
			return 1
		}
	done
	for file in "$lock_output_root"/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh' || continue
		relative="apps/$(basename "$(dirname "$file")")/images.lock.env"
		install -d -m 700 "$backup/apps/$(basename "$(dirname "$file")")"
		cp -p "$file" "$backup/$relative" || {
			rm -rf -- "$stage" "$backup"
			return 1
		}
	done
	if ! remove_generated || ! copy_generated_stage "$stage"; then
		# Best-effort rollback is deliberately explicit. The old set is restored
		# before the caller reports failure, so a partial workflow set is never
		# left for Woodpecker to execute.
		remove_generated || true
		for file in "$backup"/*.yml; do
			[[ -f "$file" ]] || continue
			cp -p "$file" "$output/$(basename "$file")" || true
		done
		for file in "$backup"/apps/*/images.lock.env; do
			[[ -f "$file" ]] || continue
			target="$lock_output_root/$(basename "$(dirname "$file")")/images.lock.env"
			install -d -m 700 "$(dirname "$target")"
			cp -p "$file" "$target" || true
		done
		rm -rf -- "$stage" "$backup"
		return 1
	fi
	rm -rf -- "$stage" "$backup"
}

case "$mode" in
generate) generate_transaction || die 'unable to apply generated workflow set atomically' ;;
--check)
	tmp="$(mktemp -d)"
	trap 'rm -rf -- "$tmp"' EXIT
	real_output="$output"
	real_lock_output_root="$lock_output_root"
	output="$tmp"
	lock_output_root="$tmp/apps"
	render_all
	output="$real_output"
	lock_output_root="$real_lock_output_root"
	for file in "$tmp"/*.yml; do
		target="$output/$(basename "$file")"
		cmp -s "$file" "$target" || die "workflow is stale or differs: $target"
	done
	for file in "$tmp"/apps/*/images.lock.env; do
		[[ -f "$file" ]] || continue
		app="$(basename "$(dirname "$file")")"
		target="$lock_output_root/$app/images.lock.env"
		cmp -s "$file" "$target" || die "application image lock is stale or differs: $target"
	done
	for file in "$output"/*.yml; do
		[[ -f "$file" ]] || continue
		if head -n1 "$file" | grep -Fq 'generated by ops/generate-woodpecker-workflows.sh'; then
			[[ -f "$tmp/$(basename "$file")" ]] || die "stale generated workflow: $file"
		fi
	done
	check_dependency_closure
	;;
*) die 'usage: generate-woodpecker-workflows.sh [generate|--check]' ;;
esac
