render_consumer_secrets() {
	local app="$1" node="$2" dependency="$3" keys="$4" file key secret_name target_arg='' workflow_name secret_keys
	file="$output/consumer-secrets-$app-$node.yml"
	workflow_name="consumer-secrets-$app-$node"
	secret_keys="$(woodpecker_secret_keys "$app" "$keys")"
	[[ "$node" == "$leader_id" ]] || target_arg=" --target-node $node"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
when:
  - event: manual
    branch: main
    evaluate: 'MANUAL_WORKFLOW == "$workflow_name"'
EOF
	if [[ -n "$dependency" ]]; then
		printf '\ndepends_on:\n  - %s\n' "$dependency" >>"$file"
	fi
	cat >>"$file" <<EOF

labels:
  node: $node
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$node")

steps:
  secrets:
    image: llm-hub-lite/deploy-runner:current
    pull: false
EOF
	write_volumes >>"$file"
	printf '    environment:\n' >>"$file"
	while IFS= read -r key; do
		[[ -n "$key" ]] || continue
		secret_name="$(woodpecker_secret_name "$app" "$key")"
		printf '      %s:\n        from_secret: %s\n' "$key" "$secret_name" >>"$file"
	done < <(printf '%s\n' "$secret_keys" | tr ',' '\n')
	cat >>"$file" <<EOF
    commands:
      - /usr/local/bin/configure-app-secrets $app$target_arg --non-interactive
EOF
}
woodpecker_secret_name() {
	local app="$1" wanted="$2" manifest rule key name
	manifest="$root/apps/$app/manifest.env"
	while IFS= read -r rule; do
		[[ -n "$rule" ]] || continue
		key="${rule%%:*}"
		name="${rule#*:}"
		[[ "$key" =~ ^[A-Z][A-Z0-9_]*$ && "$name" =~ ^[A-Za-z_][A-Za-z0-9_-]*$ ]] ||
			die "invalid WOODPECKER_SECRET_NAMES entry: $app/$rule"
		if [[ "$key" == "$wanted" ]]; then
			printf '%s\n' "$name"
			return 0
		fi
	done < <(printf '%s\n' "$(env_value WOODPECKER_SECRET_NAMES "$manifest")" | tr ',' '\n')
	printf '%s' "$wanted" | tr '[:upper:]' '[:lower:]'
}
woodpecker_secret_keys() {
	local app="$1" keys="$2" manifest mapping rule key result=''
	manifest="$root/apps/$app/manifest.env"
	mapping="$(env_value WOODPECKER_SECRET_NAMES "$manifest")"
	# An explicit mapping is an incremental refresh contract: only mapped
	# repository secrets are injected. Unmapped keys remain sourced from the
	# host's existing root-only configuration by configure-app-secrets.
	if [[ -z "$mapping" ]]; then
		printf '%s\n' "$keys"
		return 0
	fi
	while IFS= read -r rule; do
		[[ -n "$rule" ]] || continue
		key="${rule%%:*}"
		csv_has "$keys" "$key" || continue
		result="${result:+$result,}$key"
	done < <(printf '%s\n' "$mapping" | tr ',' '\n')
	printf '%s\n' "$result"
}
conditional_secret_keys() {
	local manifest="$1" node="${2:-}" rule selector expected keys config_file override_file value result=''
	config_file="$(dirname "$manifest")/$(env_value CONFIG_FILE "$manifest")"
	override_file="$root/config/cluster/overrides/$node/$(env_value APP_ID "$manifest").env"
	while IFS= read -r rule; do
		[[ -n "$rule" ]] || continue
		selector="${rule%%=*}"
		expected="${rule#*=}"
		keys="${expected#*|}"
		expected="${expected%%|*}"
		value="$(env_value "$selector" "$override_file")"
		[[ -n "$value" ]] || value="$(env_value "$selector" "$config_file")"
		[[ "$value" == "$expected" ]] || continue
		result="${result:+$result,}$keys"
	done < <(printf '%s\n' "$(env_value CONDITIONAL_SECRET_KEYS "$manifest")" | tr ';' '\n')
	printf '%s\n' "$result"
}

render_consumer_stage() {
	local app="$1" node="$2" dependency="$3" file manifest migration_from stage_secret_keys generated_keys key secret_name
	file="$output/consumer-stage-$app-$node.yml"
	manifest="$root/apps/$app/manifest.env"
	migration_from="$(env_value IDENTITY_MIGRATION_FROM_APP_ID "$manifest")"
	write_consumer_header "$file" "$app" "$node" "$dependency"
	cat >>"$file" <<EOF
  stage:
    image: llm-hub-lite/deploy-runner:current
    pull: false
EOF
	write_volumes >>"$file"
	stage_secret_keys=''
	if [[ "$(env_value RUNTIME_ENV_PROVISION "$manifest")" == stage ]]; then
		stage_secret_keys="$(env_value NODE_SECRET_KEYS "$manifest"),$(conditional_secret_keys "$manifest" "$node")"
	fi
	if [[ -n "$stage_secret_keys" ]]; then
		generated_keys="$(env_value GENERATED_SECRET_KEYS "$manifest")"
		printf '    environment:\n' >>"$file"
		while IFS= read -r key; do
			[[ -n "$key" ]] || continue
			csv_has "$generated_keys" "$key" && continue
			secret_name="$(woodpecker_secret_name "$app" "$key")"
			printf '      %s:\n        from_secret: %s\n' "$key" "$secret_name" >>"$file"
		done < <(printf '%s\n' "$stage_secret_keys" | tr ',' '\n' | awk 'NF && !seen[$0]++')
	fi
	if [[ -n "$migration_from" ]]; then
		cat >>"$file" <<EOF
    commands:
      - bash /opt/platform/control/current/ops/migrate-app-identity.sh prepare $app
EOF
	else
		printf '    commands:\n' >>"$file"
	fi
	cat >>"$file" <<EOF
      - /usr/local/bin/configure-app-secrets $app --target-node $node --ensure-generated
EOF
	if [[ -n "$stage_secret_keys" ]]; then
		printf '      - /usr/local/bin/configure-app-secrets %s --target-node %s --non-interactive\n' "$app" "$node" >>"$file"
	fi
	if [[ -n "$migration_from" ]]; then
		cat >>"$file" <<EOF
      - DEPLOY_DEBUG_LEVEL=$deploy_debug_level CONSUMER_APP_ID=$app /usr/local/bin/platform-submit consumer-stage "\$CI_COMMIT_SHA" || { status=\$?; rollback_status=0; IDENTITY_MIGRATION_MANIFEST=/opt/platform/control/releases/"\$CI_COMMIT_SHA"/apps/$app/manifest.env bash /opt/platform/control/releases/"\$CI_COMMIT_SHA"/ops/migrate-app-identity.sh rollback $app || rollback_status=\$?; /usr/local/bin/platformctl recover || true; if [ "\$rollback_status" -ne 0 ]; then exit "\$rollback_status"; fi; exit "\$status"; }
EOF
	else
		cat >>"$file" <<EOF
      - DEPLOY_DEBUG_LEVEL=$deploy_debug_level CONSUMER_APP_ID=$app /usr/local/bin/platform-submit consumer-stage "\$CI_COMMIT_SHA"
EOF
	fi
}

