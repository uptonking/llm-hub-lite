#!/usr/bin/env bash
# shellcheck disable=SC2016,SC2129
# SC2016: Woodpecker variables must stay literal in generated YAML.
# SC2129: workflow files are assembled from successive heredocs and
# write_volumes output, so they are appended redirect-by-redirect.
set -Eeuo pipefail
umask 077

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
policy="${CLUSTER_POLICY_FILE:-$root/config/cluster/policy.env}"
output="${WOODPECKER_WORKFLOW_ROOT:-$root/.woodpecker}"
lock_output_root="$root/apps"
mode="${1:-generate}"
deployment_group_prefix='llm-hub-lite-node'

env_value() {
	local key="$1" file="$2" line value=''
	[[ -f "$file" ]] || return 0
	while IFS= read -r line || [[ -n "$line" ]]; do
		[[ "$line" == "$key="* ]] || continue
		value="${line#*=}"
	done <"$file"
	printf '%s\n' "$value"
}
value() { env_value "$1" "$policy"; }
deployment_group() {
	local node="$1"
	printf '%s-%s\n' "$deployment_group_prefix" "$node"
}
die() {
	printf 'generate-woodpecker-workflows: %s\n' "$*" >&2
	exit 1
}
deploy_debug_level="${DEPLOY_DEBUG_LEVEL:-$(value DEPLOY_DEBUG_LEVEL)}"
deploy_debug_level="${deploy_debug_level:-off}"
case "$deploy_debug_level" in off | warn | debug) ;; *) die 'DEPLOY_DEBUG_LEVEL must be off, warn, or debug' ;; esac
csv_has() {
	local csv=",${1//[[:space:]]/},"
	[[ "$csv" == *",$2,"* ]]
}
app_policy_file() {
	local manifest="$1" app rel
	app="$(env_value APP_ID "$manifest")"
	rel="$(env_value POLICY_FILE "$manifest")"
	[[ "$rel" == "cluster/apps/$app.policy" ]] || die "invalid app policy path: $manifest"
	printf '%s/config/%s\n' "$root" "$rel"
}
render_image_lock() {
	local manifest="$1" app destination key image
	app="$(env_value APP_ID "$manifest")"
	destination="$lock_output_root/$app/images.lock.env"
	install -d -m 700 "$(dirname "$destination")"
	{
		printf '# generated by ops/generate-woodpecker-workflows.sh; do not edit\n'
		for key in $(env_value IMAGE_KEYS "$manifest"); do
			[[ "$key" =~ ^[A-Z][A-Z0-9_]*$ ]] || die "invalid IMAGE_KEYS entry: $manifest/$key"
			image="$(env_value "$key" "$root/ops/images.apps.prod.env")"
			[[ "$image" =~ @sha256:[0-9a-f]{64}$ ]] || die "application image is missing or not digest-pinned: $app/$key"
			printf '%s=%s\n' "$key" "$image"
		done
	} >"$destination"
}

ids=()
followers=()
active_ids=()
reconcile_ids=()
consumer_nodes=()
active_consumer_nodes=()
retired_ids=()
ids_csv=''
while IFS= read -r id; do
	[[ -n "$id" ]] || continue
	[[ "$id" =~ ^[a-z][a-z0-9-]*$ ]] || die "invalid NODE_ID: $id"
	! csv_has "$ids_csv" "$id" || die "duplicate NODE_ID: $id"
	[[ -f "$root/config/cluster/nodes/$id.env" ]] || die "missing node descriptor: $id"
	[[ "$(env_value NODE_ID "$root/config/cluster/nodes/$id.env")" == "$id" ]] || die "descriptor NODE_ID mismatch: $id"
	state="$(env_value NODE_STATE "$root/config/cluster/nodes/$id.env")"
	case "$state" in
	joining) ;;
	draining) reconcile_ids+=("$id") ;;
	active)
		active_ids+=("$id")
		reconcile_ids+=("$id")
		;;
	retired) retired_ids+=("$id") ;;
	*) die "NODE_STATE must be joining, active, draining, or retired: $id" ;;
	esac
	ids+=("$id")
	ids_csv="${ids_csv:+$ids_csv,}$id"
done < <(printf '%s\n' "$(value NODE_IDS)" | tr ',' '\n')
((${#ids[@]} > 0)) || die 'NODE_IDS is empty'
leader_id="$(value LEADER_NODE_ID)"
repo_slug="$(value REPO_SLUG)"
[[ "$repo_slug" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die 'REPO_SLUG must be owner/repository'
csv_has "$ids_csv" "$leader_id" || die 'LEADER_NODE_ID is not in NODE_IDS'
[[ "$(env_value NODE_STATE "$root/config/cluster/nodes/$leader_id.env")" == active ]] || die "designated Leader node must be active: $leader_id"
for id in "${ids[@]}"; do
	[[ "$id" == "$leader_id" ]] && continue
	followers+=("$id")
	state="$(env_value NODE_STATE "$root/config/cluster/nodes/$id.env")"
	[[ "$state" == active || "$state" == draining ]] && consumer_nodes+=("$id")
	[[ "$state" == active ]] && active_consumer_nodes+=("$id")
done
((${#followers[@]} > 0)) || die 'at least one follower is required for consumer placement'

write_volumes() {
	cat <<'EOF'
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
      - /opt/apps/llm-hub-lite:/opt/apps/llm-hub-lite
      - /opt/platform:/opt/platform
      - /opt/backups/llm-hub-lite:/opt/backups/llm-hub-lite
      - /run/lock/llm-hub-lite:/run/lock/llm-hub-lite
      - /etc/llm-hub-lite:/etc/llm-hub-lite
      - /usr/local/bin/platform-submit:/usr/local/bin/platform-submit:ro
      - /usr/local/bin/platformctl:/usr/local/bin/platformctl:ro
      - /usr/local/bin/configure-app-secrets:/usr/local/bin/configure-app-secrets:ro
      - /usr/local/bin/configure-firewall:/usr/local/bin/configure-firewall:ro
EOF
}

write_consumer_header() {
	local file="$1" app="$2" node="$3" dependencies="$4" dependency
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
skip_clone: true
when:
  - event: push
    branch: main
    path:
      include:
        - apps/$app/**
        - config/cluster/apps/$app.policy
        - config/cluster/overrides/**/$app.env
        - apps/$app/route*.caddy
        - apps/$app/images.lock.env
      on_empty: false
EOF
	printf '\ndepends_on:\n' >>"$file"
	while IFS= read -r dependency; do
		[[ -n "$dependency" ]] && printf '  - %s\n' "$dependency" >>"$file"
	done < <(printf '%s\n' "$dependencies" | tr ',' '\n')
	printf '  - control-sync-%s\n' "$node" >>"$file"
	printf '  - name: foundation-reconcile-%s\n    optional: true\n' "$node" >>"$file"
	printf '  - name: cluster-reconcile-%s\n    optional: true\n' "$node" >>"$file"
	cat >>"$file" <<EOF

labels:
  node: $node
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$node")

steps:
EOF
}

render_control_sync() {
	local id dependency file command
	id="$1"
	# Control synchronization is node-local.  The host lock and the per-node
	# Woodpecker concurrency group preserve ordering without forcing every
	# follower to wait for the previous follower.
	dependency=''
	command='control-sync'
	if [[ "$id" == "$leader_id" ]]; then
		# Push audit is informational/API housekeeping. Run it independently so
		# planner latency or failure can never delay the real validation gate.
		dependency=''
	else
		dependency="control-sync-$leader_id"
		command='control-verify'
	fi
	file="$output/control-sync-$id.yml"
	cat >"$file" <<EOF
# generated by ops/generate-woodpecker-workflows.sh; do not edit
skip_clone: true
when:
  - event: push
    branch: main

EOF
	if [[ -n "$dependency" ]]; then
		if [[ "$id" == "$leader_id" ]]; then
			# Push audit is telemetry and optional API housekeeping. It must remain
			# visible, but a transient planner failure must never block the real
			# Leader control-sync validation gate.
			printf 'depends_on:\n  - name: %s\n    optional: true\n\n' "$dependency" >>"$file"
		else
			# Followers remain strictly gated on the Leader control-sync result.
			printf 'depends_on:\n  - %s\n\n' "$dependency" >>"$file"
		fi
	fi
	# The Leader performs the expensive full release validation. Followers
	# still fetch and verify the exact commit locally, but are gated on the
	# Leader's successful control gate before any service mutation.
	cat >>"$file" <<EOF
labels:
  node: $id
  deployment: "true"
  target: production
  repo: $repo_slug

concurrency:
  limit: 1
  group: $(deployment_group "$id")

steps:
  control-sync:
    image: llm-hub-lite/deploy-runner:current
    pull: false
EOF
	write_volumes >>"$file"
	cat >>"$file" <<EOF
    commands:
EOF
	if [[ "$command" == control-verify ]]; then
		# During a rolling upgrade a follower may still have the previous
		# platform-submit/controller installed.  That wrapper cannot parse
		# control-verify yet, so fall back to the compatible full control-sync
		# path; once this release is installed, subsequent pushes use the
		# cheaper verification-only path.
		printf '      - if [ -f /opt/platform/control/current/ops/platform-submit.sh ] && grep -q control-verify /opt/platform/control/current/ops/platform-submit.sh; then DEPLOY_DEBUG_LEVEL=%s /usr/local/bin/platform-submit control-verify "$CI_COMMIT_SHA"; else DEPLOY_DEBUG_LEVEL=%s /usr/local/bin/platform-submit control-sync "$CI_COMMIT_SHA"; fi\n' "$deploy_debug_level" "$deploy_debug_level" >>"$file"
	else
		printf '      - DEPLOY_DEBUG_LEVEL=%s /usr/local/bin/platform-submit %s "$CI_COMMIT_SHA"\n' "$deploy_debug_level" "$command" >>"$file"
	fi
}

